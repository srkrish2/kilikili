/** Maps strokes authored in their own 0–1 box into the part [x0,x1]×[y0,y1] of a combined glyph. */
function place(strokes: Pt[][], x0: number, x1: number, y0 = 0, y1 = 1): Pt[][] {
  return strokes.map((s) => s.map(([x, y]) => [x0 + x * (x1 - x0), y0 + y * (y1 - y0)] as Pt));
}

